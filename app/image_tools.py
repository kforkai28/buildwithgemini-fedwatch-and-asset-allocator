"""Image generation tools for FedWatch & Asset Allocator."""
import uuid
from typing import Any, Dict
from google import genai
from google.cloud import storage

PROJECT_ID = "qwiklabs-gcp-04-f13248a6578f"
LOCATION = "us-central1"
BUCKET_NAME = "fedwatch-asset-allocator-qwiklabs-gcp-04-f13248a6578f"

_storage_client = None


def get_storage_client() -> storage.Client:
    """Returns a singleton GCS client."""
    global _storage_client
    if _storage_client is None:
        _storage_client = storage.Client(project=PROJECT_ID)
    return _storage_client


def generate_macro_infographic(prompt: str) -> Dict[str, Any]:
    """Generates an infographic or visual chart representing macroeconomic trends or portfolio allocations.
    
    The generated visual is uploaded to the public Cloud Storage bucket and its public HTTPS URL is returned.
    
    Args:
        prompt: Detailed description of the image to generate (e.g. 'Asset allocation diagram with 60% equities and 40% bonds, minimalist vector style', 'Yield curve steepening diagram').
        
    Returns:
        Dictionary with image status, public HTTPS URL, and prompt description.
    """
    try:
        client = genai.Client(vertexai=True, project=PROJECT_ID, location=LOCATION)
        response = client.models.generate_content(
            model="gemini-2.5-flash-image",
            contents=f"Generate an image: {prompt}",
        )
        
        image_bytes = None
        for candidate in response.candidates:
            for part in candidate.content.parts:
                if part.inline_data and part.inline_data.data:
                    image_bytes = part.inline_data.data
                    mime_type = part.inline_data.mime_type or "image/png"
                    break
            if image_bytes:
                break
                
        if not image_bytes:
            return {"error": "No image data was generated by the model."}

        # Upload image to public GCS bucket
        filename = f"infographics/{uuid.uuid4().hex[:10]}.png"
        gcs = get_storage_client()
        bucket = gcs.bucket(BUCKET_NAME)
        blob = bucket.blob(filename)
        blob.upload_from_string(image_bytes, content_type=mime_type)

        public_url = f"https://storage.googleapis.com/{BUCKET_NAME}/{filename}"
        
        return {
            "status": "success",
            "image_url": public_url,
            "filename": filename,
            "description": prompt,
            "message": f"Successfully generated macro infographic and uploaded to {public_url}"
        }
    except Exception as e:
        return {"error": f"Failed to generate infographic: {str(e)}"}
